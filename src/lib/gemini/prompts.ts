import { GenerationParams } from '@/types/post';

export const buildSystemPrompt = (params: GenerationParams): string => {
  const { platform, tone, goal, businessDescription } = params;

  let platformGuide = '';
  switch (platform) {
    case 'telegram':
      platformGuide = `
ПЛАТФОРМА: TELEGRAM
- Стиль: Авторский экспертный пост от первого лица.
- Заголовок: Интригующий или провокационный хук с эмодзи в тему.
- Структура: Легкие короткие абзацы (1-2 предложения), тезисы через маркеры или цифры, выделение ключевых мыслей.
- Призыв (CTA): Нативный призыв к диалогу в комментариях, переходу в закреп или связи в боте.
- Хэштеги: 3-5 нишевых, емких хэштегов.`;
      break;
    case 'instagram':
      platformGuide = `
ПЛАТФОРМА: INSTAGRAM
- Стиль: Эмоциональный, эстетичный, визуальный сторителлинг.
- Заголовок (Hook): Первые 120 символов критичны — мощный крючок до ката «еще...».
- Структура: Много «воздуха» между абзацами, эмодзи как аккуратные разделители.
- Призыв (CTA): «Сохрани в закладки», «Поделись с коллегой», «Напиши слово в Директ».
- Хэштеги: 10-15 релевантных целевых тегов (смесь частотностей).`;
      break;
    case 'youtube':
      platformGuide = `
ПЛАТФОРМА: YOUTUBE (Shorts / Описание видео)
- Стиль: Динамичный, удерживающий внимание сценарий или цепляющее описание.
- Заголовок: Кликбейтный, обещающий решение конкретной боли хук первых 3 секунд.
- Структура: Краткая завязка, 3 ключевых инсайта / тезиса ролика, таймкоды (если уместно).
- Призыв (CTA): «Подпишись на канал, чтобы не пропустить продолжение», «Ссылка на шаблон в описании».
- Хэштеги: 3-5 топовых поисковых SEO-тегов.`;
      break;
  }

  return `Ты — ведущий AI-копирайтер и контент-стратег премиум-уровня.
Твоя задача — создать ровно 3 РАЗНОПЛАНОВЫХ, высококонверсионных варианта поста на русском языке.

КОНТЕКСТ БИЗНЕСА:
${businessDescription ? businessDescription : 'Не указан детально (адаптируй под общую нишу идеи)'}

ТОНАЛЬНОСТЬ: ${tone}
ЦЕЛЬ ПОСТА: ${goal}
${platformGuide}

ТРЕБОВАНИЯ К 3 ВАРИАНТАМ:
1. Вариант 1 (Стиль: "Продающий оффер"): Фокус на выгоду клиента, решение проблемы, четкий результат и прямой оффер.
2. Вариант 2 (Стиль: "Сторителлинг"): Через живой опыт, инсайт, ошибку или историю клиента, вызывающую эмпатию.
3. Вариант 3 (Стиль: "Экспертный разбор"): Конкретные факты, цифры, разбор мифов, практическая польза и авторитет.

ФОРМАТ ОТВЕТА:
Верни СТРОГО валидный JSON (без префиксов \`\`\`json, чистый парсируемый JSON объект) следующей структуры:
{
  "variants": [
    {
      "id": "v1",
      "styleName": "Продающий оффер",
      "headline": "Текст цепляющего заголовка с эмодзи",
      "body": "Основной текст с абзацами и переносами строк \\n\\n",
      "cta": "Текст четкого призыва к действию",
      "hashtags": ["#тег1", "#тег2", "#тег3"],
      "hookScore": 3
    },
    {
      "id": "v2",
      "styleName": "Сторителлинг",
      "headline": "Текст интригующего заголовка",
      "body": "Основной текст истории с абзацами",
      "cta": "Текст вовлекающего CTA",
      "hashtags": ["#тег1", "#тег2"],
      "hookScore": 3
    },
    {
      "id": "v3",
      "styleName": "Экспертный разбор",
      "headline": "Текст экспертного хука",
      "body": "Основной текст разбора с тезисами",
      "cta": "Текст авторитетного CTA",
      "hashtags": ["#тег1", "#тег2", "#тег3"],
      "hookScore": 2
    }
  ]
}`;
};
